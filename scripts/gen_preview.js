const CH_W = 6, CH_H = 10;

// ============================================================
//  Color helpers
// ============================================================
function hex2rgb(hex) {
  const h = hex.replace('#', '');
  return [
    parseInt(h.substring(0, 2), 16),
    parseInt(h.substring(2, 4), 16),
    parseInt(h.substring(4, 6), 16),
  ];
}

// ============================================================
//  PNG encoder (raw RGB, no interlace, filter=0)
// ============================================================
function crc32(buf) {
  let c = 0xFFFFFFFF;
  for (let i = 0; i < buf.length; i++) {
    c ^= buf[i];
    for (let j = 0; j < 8; j++) c = (c >>> 1) ^ (c & 1 ? 0xEDB88320 : 0);
  }
  return (c ^ 0xFFFFFFFF) >>> 0;
}

function makeChunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const tb = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(tb));
  return Buffer.concat([len, tb, crc]);
}

function encodePNG(w, h, pixels) {
  const sig = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8;  // bit depth
  ihdr[9] = 2;  // RGB
  const raw = Buffer.alloc(h * (1 + w * 3));
  let off = 0;
  for (let y = 0; y < h; y++) {
    raw[off++] = 0; // filter none
    const rowOff = y * w * 3;
    for (let x = 0; x < w; x++) {
      const px = (rowOff + x * 3);
      raw[off++] = pixels[px];
      raw[off++] = pixels[px + 1];
      raw[off++] = pixels[px + 2];
    }
  }
  const compressed = zlib.deflateSync(raw);
  return Buffer.concat([
    sig,
    makeChunk('IHDR', ihdr),
    makeChunk('IDAT', compressed),
    makeChunk('IEND', Buffer.alloc(0)),
  ]);
}

// ============================================================
//  Pixel buffer operations
// ============================================================
class Canvas {
  constructor(w, h) {
    this.w = w;
    this.h = h;
    this.buf = Buffer.alloc(w * h * 3);
  }

  fillRect(x, y, cw, ch, rgb) {
    const x0 = Math.max(0, Math.round(x));
    const y0 = Math.max(0, Math.round(y));
    const x1 = Math.min(this.w, x0 + Math.round(cw));
    const y1 = Math.min(this.h, y0 + Math.round(ch));
    for (let py = y0; py < y1; py++) {
      const ro = py * this.w * 3;
      for (let px = x0; px < x1; px++) {
        const o = ro + px * 3;
        this.buf[o] = rgb[0];
        this.buf[o + 1] = rgb[1];
        this.buf[o + 2] = rgb[2];
      }
    }
  }

  drawChar(ch, cx, cy, rgb) {
    const g = GLYPH[ch] || GLYPH['?'];
    if (!g) return CH_W;
    const x0 = Math.max(0, Math.round(cx));
    const y0 = Math.max(0, Math.round(cy));
    for (let r = 0; r < CH_H; r++) {
      const py = y0 + r;
      if (py >= this.h) continue;
      const bits = g[r];
      for (let c = 0; c < CH_W; c++) {
        if ((bits >> (CH_W - 1 - c)) & 1) {
          const px = x0 + c;
          if (px >= this.w) continue;
          const o = (py * this.w + px) * 3;
          this.buf[o] = rgb[0];
          this.buf[o + 1] = rgb[1];
          this.buf[o + 2] = rgb[2];
        }
      }
    }
    return CH_W;
  }

  drawText(text, x, y, rgb) {
    let cx = x;
    for (const ch of text) {
      cx += this.drawChar(ch, cx, y, rgb);
    }
    return cx - x;
  }

  toPNG() {
    return encodePNG(this.w, this.h, this.buf);
  }
}

